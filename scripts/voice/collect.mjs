#!/usr/bin/env node
// Collects every spoken CUTSCENE line for the voice render (DESIGN.md §21). Voices play
// only in cutscenes — the prologue, the story scenes in play, the mission scenes and the
// boss intros, everything the story engine (src/story/*) plays. Villagers, Lyra's own
// words in the world and in the chat, and people talking to each other are text only.
//
//   node scripts/voice/collect.mjs            -> scripts/voice/lines.json (git-ignored)
//   node scripts/voice/collect.mjs --list     print the lines, one per row
//
// Each line: { key, line, speaker, text, mood, script, place, order }
//   key    lineKey(speaker, text) from src/audio/voice_key.js: the game finds a clip by
//          the words it is about to say, so a changed line simply needs a new render
//   line   the step's own id ('prologue.07')
//   place  where the voice is heard: null (open air), 'room', 'chapel', 'hall' (stone),
//          'memory' (a remembered voice) — the render adds a room or a muffle
//
// Scenes built at the moment from who is alive (a funeral, the Moot) are not fixed lines
// and stay text only.

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { lineKey } from '../../src/audio/voice_key.js';
import { SCRIPTS, isSpoken } from '../../src/story/scripts.js';
import { MISSION_SCRIPTS } from '../../src/story/scripts_missions.js';
import { BOSS_SCRIPTS } from '../../src/story/scripts_bosses.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, 'lines.json');

// Scenes whose voices are heard indoors, and from which panel or step on.
const PLACE = {
  chapel_candles: 'chapel',
  flames_rise: 'chapel',
  boss_warden: 'hall',
};
// Speakers who are only ever heard remembered (Maren is gone; she speaks in Lyra's stories).
const REMEMBERED = new Set(['maren']);

export function collect() {
  const scripts = { ...SCRIPTS, ...MISSION_SCRIPTS, ...BOSS_SCRIPTS };
  const out = [];
  const seen = new Set();
  let order = 0;
  for (const [id, script] of Object.entries(scripts)) {
    let inWorld = false;
    for (const st of script.steps || []) {
      if (st.world === 'begin') inWorld = true;
      if (st.world === 'end') inWorld = false;
      if (!isSpoken(st)) continue;
      const speaker = st.narrate != null ? 'narrator' : st.say;
      const text = st.narrate != null ? st.narrate : st.text;
      const key = lineKey(speaker, text);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      let place = PLACE[id] || null;
      if (id === 'prologue' && inWorld) place = 'room'; // the Wayhouse bedroom
      if (REMEMBERED.has(speaker)) place = 'memory';
      if (speaker === 'narrator') place = null; // the Void has its own space
      out.push({ key, line: st.key, speaker, text, mood: st.mood || null, script: id, place, order: order++ });
    }
  }
  return out;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const lines = collect();
  if (process.argv.includes('--list')) {
    for (const l of lines) console.log(`${l.line.padEnd(18)} ${l.speaker.padEnd(9)} ${(l.mood || '').padEnd(9)} ${(l.place || '').padEnd(7)} ${l.text}`);
  }
  writeFileSync(OUT, JSON.stringify({ note: 'Generated by scripts/voice/collect.mjs: every spoken cutscene line.', lines }, null, 1) + '\n');
  const by = {};
  for (const l of lines) by[l.speaker] = (by[l.speaker] || 0) + 1;
  console.log(`collect: ${lines.length} cutscene lines -> ${path.relative(process.cwd(), OUT)}  ${JSON.stringify(by)}`);
}
