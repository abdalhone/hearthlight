// (src/missions/system.js). Every mission is written in its giver's voice (docs/LORE.md
// §6, §11) and never says a truth LORE §9 keeps hidden (tests/missions.test.mjs checks
// every line). Together they grant every shape, essence and twist except the starting
// bolt and the five bosses' ten drops, each exactly once (raw, the violet the stranger
// wakes weaving, is named in the first lesson).
//
// Mission:
// { id, giver: npcId | 'lyra' | 'board', title, summary, hint,
//   requires: { missions: [ids], done: n, day: n, trust: n, opinion: n, level: n,
//               essences: n (non-raw essences unlocked), quest: n (Maren stage index), flags: [] },
//   danger: placeId (Lyra weighs coming along through her request API) | null,
//   turnIn: npcId (default: the giver) | null (rewards on the last objective),
//   offer, accept, decline, progress, turnin: [lines in the giver's voice],
//   board: 'the notice as pinned' (board missions),
//   objectives: [{ type, label, ... }] (one after another; see tracker.js),
//   rewards: [{ magic: {kind, id} } | { coins } | { xp } | { maxMana } | { slot: 'weave'|'essence'|'twist' } | { items: [[id, qty]] }
//             | { price: id } | { unlock: { kind, id } } | { points: n }   (DESIGN §25–26; src/progression/index.js grants these)],
//   lyra: { accept?, done? } (her own words when she is near),
//   tip: string | { desk, touch } (a how-to toast after it is done) }
//
// Times of day for `when`: 'day' 7–18, 'dusk' 17.5–21, 'evening' 17.5–24, 'night'
// (20.5–5), or { from, to } in hours.

